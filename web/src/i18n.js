const initial = typeof window !== 'undefined' ? window.__appLang || localStorage.getItem('ticket_lang') || 'zh' : 'zh'

/** 当前语言，响应式；模板里调用 t() 会自动跟随切换 */
export const lang = ref(dicts[initial] ? initial : 'zh')

export function setLang(next) {
  if (!dicts[next]) return
  lang.value = next
  if (typeof window !== 'undefined') {
    window.__appLang = next
    localStorage.setItem('ticket_lang', next)
  }
}

export const availableLangs = [
  { key: 'zh', label: '简体中文' },
  { key: 'en', label: 'English' },
]

export const t = (key, vars) => {
  let s = dicts[lang.value]?.[key] ?? dicts.zh[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}
